/*
 * RZIP Long-Range Redundancy Elimination Compression Algorithm
 * Compatible with AlgorithmFramework
 * (c)2006-2025 Hawkynt
 *
 * RZIP was devised by Andrew Tridgell, growing out of the block-matching ideas behind
 * rsync and first described in his PhD thesis "Efficient Algorithms for Sorting and
 * Synchronization" (Australian National University, 1999). The original rzip tool
 * (https://rzip.samba.org/) builds a hash-indexed dictionary across the WHOLE input
 * file (historically up to 900 MB) rather than a small sliding window, so it can find
 * and encode duplicated regions at arbitrary distances - something ordinary LZ77/DEFLATE
 * cannot do because their history buffer is capped at 32-64 KB. Stage 1 emits a compact
 * stream of literal runs and (offset,length) copy tokens; stage 2 pipes that stream
 * through an external general-purpose compressor (bzip2) for entropy coding.
 *
 * Note: this implementation replicates rzip's stage-1 design (a rolling hash built over
 * the entire processed input, so matches can be found and copied from anywhere already
 * seen, not just a recent window) and, because every algorithm file in this project must
 * be a self-contained standalone module with no external tooling or other files to import,
 * adds its own lightweight order-0 canonical Huffman entropy stage for the literal bytes
 * in place of the external bzip2 stage upstream rzip relies on. The stream therefore
 * carries the "RZIP" signature and version of the upstream container but is NOT
 * interchangeable with files written by the upstream tool.
 */

