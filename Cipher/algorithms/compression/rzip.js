  /**
   * @param {int32} count - Number of bytes
   * @param {float64} seed - Generator seed
   * @returns {uint8[]} Reproducible pseudo-random bytes
   */
  function genPseudoRandomBytes(count, seed) {
    /** @type {uint8[]} */
    const bytes = [];
    /** @type {float64} */
    let state = seed % 4294967296;
    for (let i = 0; i < count; ++i) {
      state = (state * 1664525 + 1013904223) % 4294967296;
      /** @type {float64} */
      const byte = Math.floor(state / 16777216) % 256;
      bytes.push(byte);
    }
    return bytes;
  }

  /**
   * @param {int32} size - Number of entries
   * @returns {int32[]} Plain array of zeros
   */
  function zeroArray(size) {
    /** @type {int32[]} */
    const arr = new Array(size);
    for (let i = 0; i < size; ++i) {
      arr[i] = 0;
    }
    return arr;
  }

