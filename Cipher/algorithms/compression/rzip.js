  // ===== VARIABLE-LENGTH INTEGER ENCODING (LEB128-style, arithmetic only) =====

  /**
   * Read position shared by the stream parsers.
   */
  class ReadCursor {
    /**
     * @param {int32} p - Initial byte position
     */
    constructor(p) {
      /** @type {int32} */
      this.p = p;
    }
  }

  /**
   * @param {uint8[]} out - Output stream, appended to
   * @param {float64} value - Non-negative integer
   */
  function varIntWrite(out, value) {
    /** @type {float64} */
    let v = value;
    for (;;) {
      /** @type {float64} */
      const byte = v % 128;
      v = Math.floor(v / 128);
      if (v > 0) {
        out.push(byte + 128);
      } else {
        out.push(byte);
        break;
      }
    }
  }

  // A read past the end yields an undefined byte and never terminates, as before.
  /**
   * @param {uint8[]} bytes - Input stream
   * @param {ReadCursor} pos - Read position, advanced
   * @returns {float64} Decoded integer
   */
  function varIntRead(bytes, pos) {
    /** @type {float64} */
    let result = 0;
    /** @type {float64} */
    let mult = 1;
    for (;;) {
      /** @type {float64} */
      const byte = bytes[pos.p++];
      result += (byte % 128) * mult;
      if (byte < 128) {
        break;
      }
      mult *= 128;
    }
    return result;
  }

  // ===== BIT-LEVEL I/O FOR THE LITERAL ENTROPY STAGE =====
  // A private, self-consistent bit packing (bits are appended LSB-first within each byte);
  // encoder and decoder only need to agree with each other, not with any external format.

  class BitWriter {
    constructor() {
      /** @type {uint8[]} */
      this.bytes = [];
      /** @type {uint32} */
      this.buffer = 0;
      /** @type {int32} */
      this.bitCount = 0;
    }

    /**
     * @param {uint32} bit - Bit to append
     */
    writeBit(bit) {
      this.buffer = OpCodes.Or32(this.buffer, OpCodes.Shl32(bit, this.bitCount));
      ++this.bitCount;
      if (this.bitCount === 8) {
        this.bytes.push(OpCodes.And32(this.buffer, 0xFF));
        this.buffer = 0;
        this.bitCount = 0;
      }
    }

    // Writes 'length' bits of 'value', most-significant bit first.
    /**
     * @param {float64} value - Code bits
     * @param {int32} length - Bit count
     */
    writeBits(value, length) {
      for (let i = length - 1; i >= 0; --i) {
        /** @type {uint32} */
        const bit = OpCodes.And32(OpCodes.Shr32(value, i), 1);
        this.writeBit(bit);
      }
    }

    /**
     * @returns {uint8[]} All bytes written so far
     */
    flush() {
      if (this.bitCount > 0) {
        this.bytes.push(OpCodes.And32(this.buffer, 0xFF));
        this.buffer = 0;
        this.bitCount = 0;
      }
      return this.bytes;
    }
  }

  class BitReader {
    /**
     * @param {uint8[]} bytes - Input
     */
    constructor(bytes) {
      /** @type {uint8[]} */
      this.bytes = bytes;
      /** @type {int32} */
      this.bytePos = 0;
      /** @type {uint32} */
      this.buffer = 0;
      /** @type {int32} */
      this.bitPos = 8;
    }

    /**
     * @returns {uint32} Next bit
     */
    readBit() {
      if (this.bitPos === 8) {
        if (this.bytePos >= this.bytes.length) {
          throw new Error('Unexpected end of literal bit stream');
        }
        this.buffer = this.bytes[this.bytePos++];
        this.bitPos = 0;
      }
      /** @type {uint32} */
      const bit = OpCodes.And32(OpCodes.Shr32(this.buffer, this.bitPos), 1);
      ++this.bitPos;
      return bit;
    }
  }

  // ===== CANONICAL HUFFMAN CODING (order-0, 256-symbol byte alphabet) =====

  // The decoding tree is kept as node rows (symbol, zero child, one child; -1
  // for none). Codes are inserted in symbol order exactly as the former object
  // tree did: a leaf replaces whatever hung at its slot, a longer code walks
  // through (and extends) whatever node it meets, so even an inconsistent
  // length table decodes as before.
  class HuffmanTree {
    constructor() {
      /** @type {boolean} */
      this.hasRoot = false;
      /** @type {int32[]} */
      this.nodeSymbol = [];
      /** @type {int32[]} */
      this.nodeZero = [];
      /** @type {int32[]} */
      this.nodeOne = [];
      /** @type {boolean} */
      this.hasCodes = false;
      /** @type {boolean[]} */
      this.codePresent = [];
      /** @type {float64[]} */
      this.codeValues = [];
      /** @type {int32[]} */
      this.codeLengths = [];
    }

    /**
     * @param {int32} symbol - Leaf symbol, -1 for an inner node
     * @returns {int32} New node index
     */
    _newNode(symbol) {
      /** @type {int32} */
      const index = this.nodeSymbol.length;
      this.nodeSymbol.push(symbol);
      this.nodeZero.push(-1);
      this.nodeOne.push(-1);
      return index;
    }

    /**
     * @param {int32} node - Parent node
     * @param {uint32} bit - Branch
     * @returns {int32} Child node, -1 when absent
     */
    _child(node, bit) {
      return bit ? this.nodeOne[node] : this.nodeZero[node];
    }

    /**
     * @param {int32} node - Parent node
     * @param {uint32} bit - Branch
     * @param {int32} child - Child node
     */
    _setChild(node, bit, child) {
      if (bit) {
        this.nodeOne[node] = child;
      } else {
        this.nodeZero[node] = child;
      }
    }

    // A length byte read past the end of the stream is undefined: it gets a
    // code entry but no code bits and no tree path, as before.
    /**
     * @param {int32[]} lengths - Code length per symbol
     * @returns {HuffmanTree} Canonical code and decoding tree
     */
    static buildFromLengths(lengths) {
      /** @type {HuffmanTree} */
      const tree = new HuffmanTree();
      /** @type {int32} */
      let maxLen = 0;
      for (let s = 0; s < lengths.length; ++s) {
        if (lengths[s] > maxLen) {
          maxLen = lengths[s];
        }
      }
      if (maxLen === 0) {
        return tree;
      }

      /** @type {int32[]} */
      const blCount = zeroArray(maxLen + 1);
      for (let s = 0; s < lengths.length; ++s) {
        if (lengths[s] > 0) {
          ++blCount[lengths[s]];
        }
      }

      /** @type {float64[]} */
      const nextCode = [];
      for (let bits = 0; bits <= maxLen; ++bits) {
        nextCode.push(0);
      }
      /** @type {float64} */
      let code = 0;
      blCount[0] = 0;
      for (let bits = 1; bits <= maxLen; ++bits) {
        /** @type {float64} */
        const count = blCount[bits - 1];
        code = OpCodes.ToUint32((code + count) * 2);
        nextCode[bits] = code;
      }

      for (let symbol = 0; symbol < lengths.length; ++symbol) {
        /** @type {int32} */
        const len = lengths[symbol];
        tree.codePresent.push(len !== 0);
        tree.codeValues.push(0);
        tree.codeLengths.push(0);
        if (len > 0) {
          tree.codeValues[symbol] = nextCode[len];
          tree.codeLengths[symbol] = len;
          ++nextCode[len];
        }
      }

      tree.hasRoot = true;
      tree._newNode(-1);
      for (let symbol = 0; symbol < lengths.length; ++symbol) {
        /** @type {int32} */
        const length = tree.codeLengths[symbol];
        if (length === 0) {
          continue;
        }

        /** @type {int32} */
        let node = 0;
        /** @type {float64} */
        const symCode = tree.codeValues[symbol];

        for (let i = length - 1; i >= 0; --i) {
          /** @type {uint32} */
          const bit = OpCodes.And32(OpCodes.Shr32(symCode, i), 1);

          if (i === 0) {
            /** @type {int32} */
            const leaf = tree._newNode(symbol);
            tree._setChild(node, bit, leaf);
          } else {
            /** @type {int32} */
            let next = tree._child(node, bit);
            if (next < 0) {
              next = tree._newNode(-1);
              tree._setChild(node, bit, next);
            }
            node = next;
          }
        }
      }

      tree.hasCodes = true;
      return tree;
    }

    /**
     * @param {BitReader} bitReader - Input bits
     * @returns {int32} Decoded symbol
     */
    decode(bitReader) {
      if (!this.hasRoot) {
        throw new Error('Invalid Huffman tree');
      }
      /** @type {int32} */
      let node = 0;

      while (this.nodeSymbol[node] < 0) {
        /** @type {uint32} */
        const bit = bitReader.readBit();
        node = this._child(node, bit);
        if (node < 0) {
          throw new Error('Invalid Huffman code');
        }
      }

      return this.nodeSymbol[node];
    }
  }

  /**
   * @param {int32} node - Subtree root
   * @param {int32} depth - Depth of that root
   * @param {int32[]} lengths - Code length per symbol, filled in
   * @param {int32[]} nodeSymbol - Leaf symbol per node, -1 for inner nodes
   * @param {int32[]} nodeLeft - Left child per node
   * @param {int32[]} nodeRight - Right child per node
   */
  function assignDepths(node, depth, lengths, nodeSymbol, nodeLeft, nodeRight) {
    if (nodeSymbol[node] >= 0) {
      lengths[nodeSymbol[node]] = depth;
      return;
    }
    assignDepths(nodeLeft[node], depth + 1, lengths, nodeSymbol, nodeLeft, nodeRight);
    assignDepths(nodeRight[node], depth + 1, lengths, nodeSymbol, nodeLeft, nodeRight);
  }

  // Builds a set of prefix-free code lengths (one per byte value 0-255) from observed
  // frequencies using a classic bottom-up Huffman merge. Symbols that never occur keep
  // length 0 (no code). A single distinct symbol is forced to length 1.
  // Each round stably orders the working list by frequency (equal frequencies
  // keep their list order), takes the first two nodes and appends their merge.
  /**
   * @param {int32[]} freqs - Frequency per byte value
   * @returns {int32[]} Code length per byte value
   */
  function buildHuffmanLengths(freqs) {
    /** @type {int32[]} */
    const symbols = [];
    for (let s = 0; s < 256; ++s) {
      if (freqs[s] > 0) {
        symbols.push(s);
      }
    }

    /** @type {int32[]} */
    const lengths = zeroArray(256);
    if (symbols.length === 0) {
      return lengths;
    }
    if (symbols.length === 1) {
      lengths[symbols[0]] = 1;
      return lengths;
    }

    /** @type {float64[]} */
    const nodeFreq = [];
    /** @type {int32[]} */
    const nodeSymbol = [];
    /** @type {int32[]} */
    const nodeLeft = [];
    /** @type {int32[]} */
    const nodeRight = [];
    /** @type {int32[]} */
    let heap = [];
    for (let k = 0; k < symbols.length; ++k) {
      nodeFreq.push(freqs[symbols[k]]);
      nodeSymbol.push(symbols[k]);
      nodeLeft.push(-1);
      nodeRight.push(-1);
      heap.push(k);
    }

    while (heap.length > 1) {
      for (let i = 1; i < heap.length; ++i) {
        /** @type {int32} */
        const item = heap[i];
        /** @type {int32} */
        let j = i - 1;
        while (j >= 0 && nodeFreq[heap[j]] > nodeFreq[item]) {
          heap[j + 1] = heap[j];
          --j;
        }
        heap[j + 1] = item;
      }
      /** @type {int32} */
      const a = heap[0];
      /** @type {int32} */
      const b = heap[1];
      heap = heap.slice(2);
      /** @type {int32} */
      const merged = nodeFreq.length;
      nodeFreq.push(nodeFreq[a] + nodeFreq[b]);
      nodeSymbol.push(-1);
      nodeLeft.push(a);
      nodeRight.push(b);
      heap.push(merged);
    }

    assignDepths(heap[0], 0, lengths, nodeSymbol, nodeLeft, nodeRight);

    return lengths;
  }

  // ===== LONG-RANGE MATCH INDEX =====

  // Rolling-hash buckets keyed by the exact 32-bit hash (open addressing).
  // Only lookups by key are made, so the slot layout never affects output.
  class HashBuckets {
    /**
     * @param {int32} maxKeys - Upper bound on distinct keys inserted
     */
    constructor(maxKeys) {
      /** @type {int32} */
      let bits = 1;
      while (OpCodes.Shl32(1, bits) < maxKeys * 2) {
        ++bits;
      }
      /** @type {int32} */
      this.bits = bits;
      /** @type {int32} */
      this.mask = OpCodes.Shl32(1, bits) - 1;
      /** @type {uint32[]} */
      this.keys = new Uint32Array(this.mask + 1);
      /** @type {uint8[]} */
      this.used = new Uint8Array(this.mask + 1);
      /** @type {int32[][]} */
      this.buckets = new Array(this.mask + 1);
    }

    /**
     * @param {uint32} h - Key
     * @returns {int32} Slot holding the key, or the free slot where it belongs
     */
    _probe(h) {
      /** @type {int32} */
      let slot = OpCodes.Shr32(OpCodes.Mul32(h, 0x9E3779B1), 32 - this.bits);
      while (this.used[slot] !== 0 && this.keys[slot] !== h) {
        slot = OpCodes.And32(slot + 1, this.mask);
      }
      return slot;
    }

    /**
     * @param {uint32} h - Key
     * @returns {int32} Slot of the key's bucket, -1 when absent
     */
    find(h) {
      /** @type {int32} */
      const slot = this._probe(h);
      return this.used[slot] !== 0 ? slot : -1;
    }

    /**
     * Appends a position to the key's bucket, dropping the oldest beyond cap.
     * @param {uint32} h - Key
     * @param {int32} pos - Position
     * @param {int32} cap - Bucket capacity
     */
    insert(h, pos, cap) {
      /** @type {int32} */
      const slot = this._probe(h);
      if (this.used[slot] === 0) {
        this.used[slot] = 1;
        this.keys[slot] = h;
        /** @type {int32[]} */
        const fresh = [];
        this.buckets[slot] = fresh;
      }
      /** @type {int32[]} */
      const bucket = this.buckets[slot];
      bucket.push(pos);
      if (bucket.length > cap) {
        bucket.shift();
      }
    }
  }

  /**
   * @param {uint8[]} data - Input
   * @param {int32} pos - Window start
   * @param {int32} windowSize - Window length
   * @param {uint32} base - Polynomial multiplier
   * @returns {uint32} Polynomial hash of the window, mod 2^32
   */
  function rollingHashAt(data, pos, windowSize, base) {
    /** @type {uint32} */
    let h = 0;
    for (let i = 0; i < windowSize; ++i) {
      h = OpCodes.Add32(OpCodes.Mul32(h, base), data[pos + i]);
    }
    return h;
  }

