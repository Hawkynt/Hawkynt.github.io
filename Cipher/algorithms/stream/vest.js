  /**
   * One VEST root cipher: decoded accumulator rows, counters, output taps
   * and the keying rules of its submission phase
   * @class
   */
  class VESTProfile {
    /**
     * @param {string[]} rows - Accumulator rows as hex (ROW_BYTES bytes per row)
     * @param {uint32[][]} counters - Width and feedback truth table of each counter
     * @param {int32[][]} combiner - Six accumulator bit indexes per output bit
     * @param {boolean} phase2 - Phase 2 keying (true) or ProVEST keying (false)
     */
    constructor(rows, counters, combiner, phase2) {
      /** @type {uint8[]} */
      const bytes = OpCodes.Hex8ToBytes(rows.join(''));
      /** @type {int32} Accumulator width W */
      this.width = bytes.length / ROW_BYTES;
      /** @type {int32} Output bits per round M */
      this.outputBits = combiner.length;
      /** @type {int32[]} Five input bit indexes per accumulator row */
      this.inputs = OpCodes.CreateArray(this.width * 5, 0);
      /** @type {int32[]} Bit each accumulator row writes */
      this.targets = OpCodes.CreateArray(this.width, 0);
      /** @type {uint32[]} Truth table of each accumulator row */
      this.functions = OpCodes.CreateArray(this.width, 0);
      for (let j = 0; j < this.width; j++) {
        /** @type {int32} */
        const at = j * ROW_BYTES;
        for (let k = 0; k < 5; k++) this.inputs[j * 5 + k] = OpCodes.Pack16BE(bytes[at + 2 * k], bytes[at + 2 * k + 1]);
        this.targets[j] = OpCodes.Pack16BE(bytes[at + 10], bytes[at + 11]);
        this.functions[j] = OpCodes.Pack32BE(bytes[at + 12], bytes[at + 13], bytes[at + 14], bytes[at + 15]);
      }
      /** @type {int32[]} Counter widths (10 or 11 bits) */
      this.counterWidths = OpCodes.CreateArray(COUNTERS, 0);
      /** @type {uint32[]} Counter feedback truth tables */
      this.counterFunctions = OpCodes.CreateArray(COUNTERS, 0);
      /** @type {uint32[]} Counter masks */
      this.counterMasks = OpCodes.CreateArray(COUNTERS, 0);
      for (let i = 0; i < COUNTERS; i++) {
        this.counterWidths[i] = counters[i][0];
        this.counterFunctions[i] = counters[i][1];
        this.counterMasks[i] = OpCodes.Shr32(0xFFFFFFFF, 32 - counters[i][0]);
      }
      /** @type {int32[][]} */
      this.combiner = combiner;
      /** @type {boolean} */
      this.phase2 = phase2;
      /** @type {int32} Shift of the sealing constant bits within the counters */
      this.sealShift = phase2 ? 1 : 0;
    }
  }

