/*
 * VEST Stream Cipher Family (VEST-4, VEST-8, VEST-16, VEST-32, ProVEST-32)
 * eSTREAM Phase 2 candidate (BROKEN - DO NOT USE IN PRODUCTION)
 * Compatible with AlgorithmFramework
 * (c)2006-2025 Hawkynt
 *
 * VEST (Sean O'Neil, Benjamin Gittins, Howard Landman) has four parts:
 *   - 16 RNS counters: 10- and 11-bit NLFSRs. Each shifts left by one bit;
 *     bit 0 becomes the old top bit XOR g(c0, c1, c2, c6, c7), a 5-input
 *     feedback function given as a 32-bit truth table.
 *   - a 10-bit counter diffusor, a linear combiner with feedback that
 *     compresses bit 1 of the 16 counters into 10 bits per round.
 *   - a W-bit core accumulator (an NLPFSR): accumulator bit j feeds a 5-input
 *     function f_j of five other accumulator bits (bits 0..4 form a 5x5
 *     S-box); bits j >= 5 also add x_j, bits j < 10 add diffusor bit d_j,
 *     and the result is stored at the permuted position p_j.
 *   - a linear output combiner: each of the M output bits per round is the
 *     XOR of six accumulator bits, read before the round updates the state.
 * Root ciphers: VEST-4 (W = 83, M = 4), VEST-8 (211, 8), VEST-16 (331, 16)
 * and VEST-32 (587, 32). Keystream bits are numbered least significant bit
 * first; a VEST-4 byte is two rounds, low nibble first.
 *
 * Keying of the Phase 2 root ciphers (VEST-n): every state bit starts at 1;
 * each round r = 1 .. F+15 XORs key bit (r-16+i) into bit 1 of counter i,
 * and a 1 into bit 0 of counter i when r-16+i equals F (counter 0 never gets
 * there; F is the key length in bits). Sealing runs one round, XORs the sealing
 * constant (0x2B after a key, 0xE4 after an IV) into bit 1 of counters
 * 0..7, and runs 31 more rounds. An IV is hashed eight bits per round into
 * bit 1 of counters 0..7 and then sealed. Quirk of the published reference
 * code, kept because its test vectors depend on it: the counters start as
 * whole 32-bit words of ones, so the bits above each counter's width enter
 * its first rotation and leave only bit 0 set.
 *
 * ProVEST-32 is the Phase 1 root cipher in its eSTREAM API version: other
 * counter feedback functions, permutations and output taps, a state that
 * starts at 0, F rounds that load key bit ((r+i) mod F) into counter i,
 * then the key hashed in like an IV, and sealing constants XORed into
 * bit 0 instead of bit 1.
 *
 * Authenticated encryption, hashing and family keying are not implemented.
 *
 * SECURITY STATUS: BROKEN - Joux and Reinhard ("Overtaking VEST", FSE 2007)
 * build inner collisions in the counters and the linear counter diffusor; a
 * chosen-IV attack recovers 53 bits of the keyed state.
 * USE ONLY FOR: academic research, cryptanalysis studies, historical reference.
 */

