  /**
   * Bit i of a byte string, least significant bit first within each byte
   * @param {uint8[]} bytes
   * @param {int32} i
   * @returns {uint32}
   */
  function bitAt(bytes, i) {
    return OpCodes.And32(OpCodes.Shr32(bytes[Math.floor(i / 8)], i % 8), 1);
  }

  /**
   * Bit i of a 32-bit word
   * @param {uint32} word
   * @param {int32} i
   * @returns {uint32}
   */
  function bitOf(word, i) {
    return OpCodes.And32(OpCodes.Shr32(word, i), 1);
  }

