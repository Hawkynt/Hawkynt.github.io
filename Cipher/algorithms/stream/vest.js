  /**
 * VEST cipher instance implementing Feed/Result pattern
 * @class
 * @extends {IAlgorithmInstance}
 */

  class VESTInstance extends IAlgorithmInstance {
    /**
   * Initialize Algorithm cipher instance
   * @param {VESTAlgorithm} algorithm - Parent algorithm instance
   * @param {boolean} [isInverse=false] - Decryption mode flag
   */

    constructor(algorithm, isInverse = false) {
      super(algorithm);
      /** @type {boolean} */
      this.isInverse = isInverse;
      /** @type {VESTProfile} */
      this.profile = algorithm.profile;
      /** @type {int32} */
      this.minKeyBytes = algorithm.SupportedKeySizes[0].minSize;
      /** @type {uint8[]|null} */
      this._key = null;
      /** @type {uint8[]} */
      this._iv = [];
      /** @type {uint8[]} */
      this.inputBuffer = [];
      /** @type {boolean} Whether the state reflects the current key and IV */
      this.ready = false;
      /** @type {uint32[]} RNS counters */
      this.counters = OpCodes.CreateArray(COUNTERS, 0);
      /** @type {uint8[]} Counter diffusor bits */
      this.diffusor = OpCodes.CreateArray(10, 0);
      /** @type {uint8[]} Core accumulator bits */
      this.core = OpCodes.CreateArray(this.profile.width, 0);
      /** @type {uint8[]} Keystream bytes generated but not used yet */
      this.keystream = [];
    }

    /**
   * Set encryption/decryption key
   * @param {uint8[]|null} keyBytes - Key bytes or null to clear
   * @throws {Error} If key size is invalid
   */

    set key(keyBytes) {
      if (!keyBytes) {
        this._key = null;
        this.ready = false;
        return;
      }
      if (keyBytes.length < this.minKeyBytes || keyBytes.length > 64) {
        throw new Error("Invalid VEST key size: " + keyBytes.length + " bytes. Requires " + this.minKeyBytes + " to 64 bytes");
      }
      this._key = [...keyBytes];
      this.ready = false;
    }

    /**
   * Get copy of current key
   * @returns {uint8[]|null} Copy of key bytes or null
   */

    get key() {
      return this._key ? [...this._key] : null;
    }

    /**
   * Set initialization vector
   * @param {uint8[]|null} ivBytes - IV bytes, or null/empty for none
   * @throws {Error} If IV size is invalid
   */

    set iv(ivBytes) {
      /** @type {uint8[]} */
      const iv = ivBytes ? [...ivBytes] : OpCodes.CreateArray(0, 0);
      if (iv.length > 64) {
        throw new Error("Invalid VEST IV size: " + iv.length + " bytes. Requires at most 64 bytes");
      }
      this._iv = iv;
      this.ready = false;
    }

    /**
   * Get copy of current IV
   * @returns {uint8[]} Copy of IV bytes
   */

    get iv() {
      return [...this._iv];
    }

    /**
     * @param {uint8[]|null} nonceBytes
     */
    set nonce(nonceBytes) { this.iv = nonceBytes; }

    /**
     * @returns {uint8[]}
     */
    get nonce() { return this.iv; }

    /**
   * Feed data to cipher for processing
   * @param {uint8[]} data - Input data bytes
   * @throws {Error} If key not set
   */

    Feed(data) {
      if (!data || data.length === 0) return;
      if (!this._key) {
        throw new Error("Key not set");
      }
      for (let _i = 0; _i < data.length; _i++) this.inputBuffer.push(data[_i]);
    }

    /**
   * Get cipher result (encrypted or decrypted data)
   * @returns {uint8[]} Processed output bytes
   * @throws {Error} If key not set or no data fed
   */

    Result() {
      if (!this._key) {
        throw new Error("Key not set");
      }
      if (this.inputBuffer.length === 0) {
        throw new Error("No data to process");
      }
      if (!this.ready) this._setup();

      /** @type {uint8[]} */
      const output = OpCodes.CreateArray(this.inputBuffer.length, 0);
      for (let i = 0; i < this.inputBuffer.length; i++) {
        if (this.keystream.length === 0) this._generate();
        output[i] = OpCodes.Xor8(this.inputBuffer[i], this.keystream.shift());
      }

      this.inputBuffer = [];
      return output;
    }

    // Key setup, IV loading and sealing
    _setup() {
      /** @type {VESTProfile} */
      const profile = this.profile;
      /** @type {uint8[]} */
      const key = this._key;
      /** @type {int32} */
      const keyBits = key.length * 8;
      this.keystream = OpCodes.CreateArray(0, 0);

      if (profile.phase2) {
        // Phase 2: start from all ones, slide the key through bit 1 of the counters
        this.counters = OpCodes.CreateArray(COUNTERS, 0xFFFFFFFF);
        this.diffusor = OpCodes.CreateArray(10, 1);
        this.core = OpCodes.CreateArray(profile.width, 1);
        for (let r = 1; r < keyBits + COUNTERS; r++) {
          this._round();
          for (let i = 0; i < COUNTERS; i++) {
            /** @type {int32} */
            const k = r - COUNTERS + i;
            if (k >= 0 && k < keyBits) this.counters[i] = OpCodes.Xor32(this.counters[i], OpCodes.Shl32(bitAt(key, k), 1));
            else if (k === keyBits) this.counters[i] = OpCodes.Xor32(this.counters[i], 1);
          }
        }
      } else {
        // ProVEST: start from zero, load the key cyclically, then hash it in
        this.counters = OpCodes.CreateArray(COUNTERS, 0);
        this.diffusor = OpCodes.CreateArray(10, 0);
        this.core = OpCodes.CreateArray(profile.width, 0);
        for (let r = 0; r < keyBits; r++) {
          this._round();
          for (let i = 0; i < COUNTERS; i++) {
            this.counters[i] = OpCodes.Xor32(this.counters[i], OpCodes.Shl32(bitAt(key, (r + i) % keyBits), 1));
          }
        }
        this._absorb(key);
      }
      this._seal(SEAL_KEY);

      if (this._iv.length > 0) {
        this._absorb(this._iv);
        this._seal(SEAL_IV);
      }
      this.ready = true;
    }

    /**
     * Hash bytes into the state, eight bits per round into counters 0..7
     * @param {uint8[]} data
     */
    _absorb(data) {
      for (let r = 0; r < data.length * 8; r += HASHING_COUNTERS) {
        this._round();
        for (let i = 0; i < HASHING_COUNTERS; i++) {
          this.counters[i] = OpCodes.Xor32(this.counters[i], OpCodes.Shl32(bitAt(data, r + i), 1));
        }
      }
    }

    /**
     * Seal the state with a constant: one round, the constant, 31 rounds
     * @param {uint32} constant - Sealing constant
     */
    _seal(constant) {
      this._round();
      for (let i = 0; i < HASHING_COUNTERS; i++) {
        this.counters[i] = OpCodes.Xor32(this.counters[i], OpCodes.Shl32(bitOf(constant, i), this.profile.sealShift));
      }
      for (let r = 0; r < SEALING_ROUNDS; r++) this._round();
    }

    // One round: accumulator, counter diffusor and counters all update from the old state
    _round() {
      /** @type {VESTProfile} */
      const profile = this.profile;
      /** @type {uint8[]} */
      const x = this.core;
      /** @type {uint8[]} */
      const d = this.diffusor;
      /** @type {uint32[]} */
      const c = this.counters;

      // Core accumulator
      /** @type {uint8[]} */
      const next = OpCodes.CreateArray(profile.width, 0);
      for (let j = 0; j < profile.width; j++) {
        /** @type {int32} */
        const at = j * 5;
        /** @type {uint32} */
        let index = 0;
        for (let k = 0; k < 5; k++) index = OpCodes.Or32(index, OpCodes.Shl32(x[profile.inputs[at + k]], k));
        /** @type {uint32} */
        let b = bitOf(profile.functions[j], index);
        if (j >= 5) b = OpCodes.Xor32(b, x[j]);
        if (j < 10) b = OpCodes.Xor32(b, d[j]);
        next[profile.targets[j]] = b;
      }

      // Counter diffusor
      /** @type {uint8[]} */
      const nextDiffusor = OpCodes.CreateArray(10, 0);
      for (let j = 0; j < 10; j++) {
        /** @type {uint32} */
        let b = OpCodes.Xor32(d[DIFFUSOR_SOURCE[j]], DIFFUSOR_CONSTANT[j]);
        /** @type {int32[]} */
        const sources = DIFFUSOR_COUNTERS[j];
        for (let k = 0; k < sources.length; k++) b = OpCodes.Xor32(b, bitOf(c[sources[k]], 1));
        nextDiffusor[j] = b;
      }

      // RNS counters
      for (let i = 0; i < COUNTERS; i++) {
        /** @type {int32} */
        const w = profile.counterWidths[i];
        /** @type {uint32} */
        let index = 0;
        for (let k = 0; k < COUNTER_TAP_COUNT; k++) index = OpCodes.Or32(index, OpCodes.Shl32(bitOf(c[i], COUNTER_TAPS[k]), k));
        /** @type {uint32} */
        const rotated = OpCodes.And32(OpCodes.Xor32(OpCodes.Shl32(c[i], 1), OpCodes.Shr32(c[i], w - 1)), profile.counterMasks[i]);
        c[i] = OpCodes.Xor32(rotated, bitOf(profile.counterFunctions[i], index));
      }

      this.core = next;
      this.diffusor = nextDiffusor;
    }

    // Keystream of one or more rounds, appended to this.keystream as whole bytes
    _generate() {
      /** @type {VESTProfile} */
      const profile = this.profile;
      /** @type {uint32} */
      let acc = 0;
      /** @type {int32} */
      let bits = 0;
      do {
        for (let j = 0; j < profile.outputBits; j++) {
          /** @type {int32[]} */
          const taps = profile.combiner[j];
          /** @type {uint32} */
          let b = 0;
          for (let k = 0; k < taps.length; k++) b = OpCodes.Xor32(b, this.core[taps[k]]);
          acc = OpCodes.Or32(acc, OpCodes.Shl32(b, bits % 8));
          bits++;
          if (bits % 8 === 0) {
            this.keystream.push(OpCodes.ToByte(acc));
            acc = 0;
          }
        }
        this._round();
      } while (bits % 8 !== 0);
    }
  }

