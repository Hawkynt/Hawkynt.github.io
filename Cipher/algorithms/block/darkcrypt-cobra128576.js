/*
 * COBRA-128-576 (DarkCrypt variant) Implementation
 * Compatible with AlgorithmFramework
 * (c)2006-2025 Hawkynt
 *
 * The "COBRA-128-576" block cipher as shipped in the DarkCrypt Total Commander
 * plugin (Alexander Myasnikov, "Zarya" project). Not related in design to the
 * academic COBRA-H/-S family; the name/parameters come straight from the
 * plugin's own metadata.
 *
 * Structure:
 *   - 128-bit block treated as four little-endian 32-bit words w[0..3].
 *   - 576-bit (72-byte) key.
 *   - 36 rounds over three round-robin S-box sets, each a concatenation of
 *     four 256-entry 32-bit tables used as a Blowfish-style F-box:
 *       F(set, x) = ((set[0][b3] + set[1][b2]) XOR set[2][b1]) + set[3][b0]
 *     where b3..b0 are the bytes of x from MSB to LSB. Round i (0-based) uses
 *     set index (2 - i mod 3) (i.e. set 2, 1, 0, 2, 1, 0, ...), updates word
 *     t = 3 - (i mod 4) from source word src = (t + 1) mod 4, and consumes
 *     round-key word RK[3*floor(i/3) + (2 - i mod 3)] (round keys inside each
 *     group of 3 rounds sharing an S-box set are taken in reverse order,
 *     while the groups themselves advance forward through RK):
 *       x = w[src] XOR RK[k]; w[t] = ROR32(F(set, x) XOR w[t], 1)
 *   - Pre-whitening XORs the input words with WHIT[0..3]; post-whitening
 *     XORs the round output with WHIT[4..7]. Decryption runs the 36 rounds
 *     in reverse with ROL32 in place of ROR32.
 *   - Key schedule: all working tables (36 round-key words, 3072 S-box
 *     words, 8 whitening words -- 3116 words total) start from a single
 *     static seed stream that is simply the classic Blowfish pi-digit
 *     constants (Schneier's published P-array/S-box values) extended far
 *     enough to cover this cipher's larger table set. Setup then (1) XORs
 *     the 576-bit key, read as a cyclically-repeating stream of big-endian
 *     32-bit words (wrapping every 72 bytes), into the round-key words and
 *     then the S-box words (the whitening words are left untouched by this
 *     step); (2) runs a full self-encryption pass that replaces every
 *     round-key, S-box and whitening word in turn with the output of
 *     encrypting a chaining state that starts at zero and evolves with the
 *     tables as they are rewritten; (3) re-XORs the round-key words with the
 *     same first 36 key-stream words used in step (1) (re-read from the very
 *     start of the key, not continued from where step (1) left off);
 *     (4) runs a second identical self-encryption pass.
 *
 * Test vectors verified against the DarkCrypt implementation (crypt/decrypt
 * round-trip verified). 128-bit blocks, 576-bit keys.
 * Educational only.
 */

