/*
 * Pikachu (DarkCrypt variant) Implementation
 * Compatible with AlgorithmFramework
 * (c)2006-2025 Hawkynt
 *
 * The Pikachu block cipher as implemented in the DarkCrypt Total Commander plugin
 * (Alexander Myasnikov, "Zarya" project). 64-bit block (2x32-bit words), 128-bit key.
 * A non-swapping Feistel network: each round XORs a keyed transform F(otherWord) into
 * one word, alternating which word is updated, for 6 outer iterations (12 F calls
 * total), followed by final whitening of both words. Decryption runs the same F
 * function but walks the round-key stream in exact reverse order.
 *   F(value, K0, K1): x = value XOR K0; split x into little-endian bytes a,b,c,d;
 *     mix them with byte-wise (mod 256) additions: p=(a+b); q=(a+p) [=2a+b];
 *     r=(c+d); s=(c+r) [=2c+d]; ch=(s+p); idx0=(q+r) [=2a+b+c+d]; idx1=(p+ch);
 *     idx2=ch; idx3=(r+idx0); look up one dedicated 256-byte S-box per byte
 *     position (S0[idx0], S1[idx1], S2[idx2], S3[idx3]); recombine little-endian
 *     into a 32-bit word; rotate left by 1 bit; XOR with K1.
 * Key schedule ("setup"): a 104-byte buffer is first filled by
 *     buf[i] = S0[(key[i mod 16] + i) & 0xFF] for i = 0..103 (a byte-oriented KSA
 *   seeded from the raw key), then scrambled in place for 4 passes (one pass per
 *   S-box S0..S3): a running byte `state` (initially 0) is updated per buffer byte as
 *   state = buf[i] XOR S_pass[state], buf[i] = state, chaining across the whole
 *   104-byte buffer and across all 4 passes without ever resetting `state`.
 * Each round's K0/K1 are read as little-endian 32-bit words from consecutive 8-byte
 * windows of this 104-byte buffer (round-key pointers advance by 16 bytes per outer
 * iteration, offset by 8 bytes between the two half-rounds); final whitening reuses
 * the 8-byte window at buffer offset 0x30.
 * As implemented in the DarkCrypt Total Commander plugin. Test vectors verified
 * against the DarkCrypt implementation (crypt/decrypt round-trip confirmed, plus
 * additional single-bit differential checks).
 * 64-bit blocks, 128-bit keys. Educational only.
 */

