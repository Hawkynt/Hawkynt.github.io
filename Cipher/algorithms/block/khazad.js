  /**
   * @param {int32} offset - 0 for the high words, 1 for the low words
   * @returns {uint32[][]} One half of each of the eight 64-bit tables
   */
  function buildTableHalves(offset) {
    /** @type {uint32[][]} */
    const halves = [];
    for (let t = 0; t < 8; t++) {
      const dwords = OpCodes.Hex32ToDWords(TABLE_HEX[t]);
      /** @type {uint32[]} */
      const half = new Array(256);
      for (let i = 0; i < 256; i++) half[i] = dwords[2 * i + offset];
      halves.push(half);
    }
    return halves;
  }

  /**
   * @param {int32} offset - 0 for the high words, 1 for the low words
   * @returns {uint32[]} One half of each round constant
   */
  function buildRoundConstantHalf(offset) {
    const dwords = OpCodes.Hex32ToDWords(ROUND_CONSTANT_HEX);
    /** @type {uint32[]} */
    const half = new Array(9);
    for (let i = 0; i < 9; i++) half[i] = dwords[2 * i + offset];
    return half;
  }

  /**
   * @param {uint32[]} table7Lo - Low words of T7
   * @returns {uint8[]} The S-box (low byte of each T7 entry)
   */
  function buildSbox(table7Lo) {
    /** @type {uint8[]} */
    const sbox = new Array(256);
    for (let i = 0; i < 256; i++) sbox[i] = OpCodes.And32(table7Lo[i], 0xff);
    return sbox;
  }

