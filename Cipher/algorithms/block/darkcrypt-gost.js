  class DarkCryptGostInstance extends IBlockCipherInstance {
    constructor(algorithm, isInverse = false) {
      super(algorithm);
      this.isInverse = isInverse;
      this._key = null;
      this.subkeys = null;
      this.inputBuffer = [];
      this.BlockSize = 8;
      this.KeySize = 0;
    }

    set key(keyBytes) {
      if (!keyBytes) { this._key = null; this.subkeys = null; this.KeySize = 0; return; }
      if (keyBytes.length !== 32)
        throw new Error(`Invalid key size: ${keyBytes.length} bytes. GOST-28147-89 (DarkCrypt) requires exactly 32 bytes`);
      this._key = [...keyBytes];
      this.subkeys = this._expandKey(this._key);
      this.KeySize = keyBytes.length;
    }

    get key() { return this._key ? [...this._key] : null; }

    Feed(data) {
      if (!data || data.length === 0) return;
      if (!this._key) throw new Error("Key not set");
      this.inputBuffer.push(...data);
    }

    Result() {
      if (!this._key) throw new Error("Key not set");
      if (this.inputBuffer.length === 0) throw new Error("No data fed");
      if (this.inputBuffer.length % this.BlockSize !== 0)
        throw new Error(`Input length must be multiple of ${this.BlockSize} bytes`);

      const output = [];
      for (let i = 0; i < this.inputBuffer.length; i += this.BlockSize) {
        const block = this.inputBuffer.slice(i, i + this.BlockSize);
        output.push(...(this.isInverse ? this._decryptBlock(block, this.subkeys) : this._encryptBlock(block, this.subkeys)));
      }
      this.inputBuffer = [];
      return output;
    }

    _expandKey(keyBytes) {
      const k = new Array(8);
      for (let i = 0; i < 8; i++) {
        const o = i * 4;
        k[i] = OpCodes.Pack32LE(keyBytes[o], keyBytes[o + 1], keyBytes[o + 2], keyBytes[o + 3]);
      }
      return k;
    }

    // Feistel state: A = first word, B = second word.
    // Round i (0-based): B ^= f(A,k[i]); A ^= f(B,k[i+1]) — pairs consumed two-at-a-time.
    _encryptBlock(block, k) {
      let A = OpCodes.Pack32LE(block[0], block[1], block[2], block[3]);
      let B = OpCodes.Pack32LE(block[4], block[5], block[6], block[7]);

      for (let cycle = 0; cycle < 3; cycle++) {
        for (let i = 0; i < 8; i += 2) {
          B = OpCodes.ToUint32(OpCodes.XorN(B, darkCryptGostRound(A, k[i])));
          A = OpCodes.ToUint32(OpCodes.XorN(A, darkCryptGostRound(B, k[i + 1])));
        }
      }
      for (let i = 7; i >= 0; i -= 2) {
        B = OpCodes.ToUint32(OpCodes.XorN(B, darkCryptGostRound(A, k[i])));
        A = OpCodes.ToUint32(OpCodes.XorN(A, darkCryptGostRound(B, k[i - 1])));
      }

      return [...OpCodes.Unpack32LE(B), ...OpCodes.Unpack32LE(A)];
    }

    _decryptBlock(block, k) {
      let A = OpCodes.Pack32LE(block[0], block[1], block[2], block[3]);
      let B = OpCodes.Pack32LE(block[4], block[5], block[6], block[7]);

      for (let i = 0; i < 8; i += 2) {
        B = OpCodes.ToUint32(OpCodes.XorN(B, darkCryptGostRound(A, k[i])));
        A = OpCodes.ToUint32(OpCodes.XorN(A, darkCryptGostRound(B, k[i + 1])));
      }
      for (let cycle = 0; cycle < 3; cycle++) {
        for (let i = 7; i >= 0; i -= 2) {
          B = OpCodes.ToUint32(OpCodes.XorN(B, darkCryptGostRound(A, k[i])));
          A = OpCodes.ToUint32(OpCodes.XorN(A, darkCryptGostRound(B, k[i - 1])));
        }
      }

      return [...OpCodes.Unpack32LE(B), ...OpCodes.Unpack32LE(A)];
    }
  }

