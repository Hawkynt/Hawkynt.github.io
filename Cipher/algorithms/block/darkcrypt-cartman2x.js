  class DarkCryptCartman2XInstance extends IBlockCipherInstance {
    /**
     * @param {DarkCryptCartman2XAlgorithm} algorithm - Parent algorithm
     * @param {boolean} [isInverse=false] - Decrypt instead of encrypt
     */
    constructor(algorithm, isInverse = false) {
      super(algorithm);
      this.isInverse = isInverse;
      /** @type {boolean} */
      this._hasKey = false;
      /** @type {CartmanTables|null} */
      this._tables = null;
      /** @type {uint8[]|null} */
      this._fwd = null;
      /** @type {uint8[]|null} */
      this._inv = null;
      /** @type {uint8[]} */
      this.inputBuffer = [];
      this.BlockSize = 16;
      this.KeySize = 0;
    }

    /**
     * @param {uint8[]|null} keyBytes - Key bytes, or null to clear
     */
    set key(keyBytes) {
      if (!keyBytes) { this._hasKey = false; this._tables = null; this._fwd = null; this._inv = null; this.KeySize = 0; return; }
      if (keyBytes.length !== 128)
        throw new Error("Invalid key size: " + keyBytes.length + " bytes. Cartman-2X (DarkCrypt) requires exactly 128 bytes");
      const k1 = keyBytes.slice(0, 64), k2 = keyBytes.slice(64, 128);
      const tFirst = buildTables(k1);
      const banks = buildSboxes(k1, tFirst);
      this._tables = buildTables(k2);
      this._fwd = banks[0];
      this._inv = banks[1];
      this._hasKey = true;
      this.KeySize = keyBytes.length;
    }

    /**
     * @returns {uint8[]|null} Copy of the key, or null
     */
    get key() { return this._hasKey ? true : null; }

    Feed(data) {
      if (!data || data.length === 0) return;
      if (!this._hasKey) throw new Error("Key not set");
      for (let _i = 0; _i < data.length; _i++) this.inputBuffer.push(data[_i]);
    }

    Result() {
      if (!this._hasKey) throw new Error("Key not set");
      if (this.inputBuffer.length === 0) throw new Error("No data fed");
      if (this.inputBuffer.length % this.BlockSize !== 0)
        throw new Error("Input length must be multiple of " + this.BlockSize + " bytes");

      /** @type {uint8[]} */
      const output = [];
      for (let i = 0; i < this.inputBuffer.length; i += this.BlockSize) {
        const block = this.inputBuffer.slice(i, i + this.BlockSize);
        output.push(...(this.isInverse ? this._decryptBlock(block) : this._encryptBlock(block)));
      }
      this.inputBuffer = [];
      return output;
    }

    /**
     * @param {uint8[]} block - Input block
     * @returns {uint8[]} Output block
     */
    _encryptBlock(block) {
      /** @type {uint32[]} */
      const X = [
        OpCodes.Pack32LE(block[0], block[1], block[2], block[3]),
        OpCodes.Pack32LE(block[4], block[5], block[6], block[7]),
        OpCodes.Pack32LE(block[8], block[9], block[10], block[11]),
        OpCodes.Pack32LE(block[12], block[13], block[14], block[15])
      ];
      cryptWords(X, this._tables, this._fwd);
      return [...OpCodes.Unpack32LE(X[0]), ...OpCodes.Unpack32LE(X[1]),
              ...OpCodes.Unpack32LE(X[2]), ...OpCodes.Unpack32LE(X[3])];
    }

    /**
     * @param {uint8[]} block - Input block
     * @returns {uint8[]} Output block
     */
    _decryptBlock(block) {
      /** @type {uint32[]} */
      const X = [
        OpCodes.Pack32LE(block[0], block[1], block[2], block[3]),
        OpCodes.Pack32LE(block[4], block[5], block[6], block[7]),
        OpCodes.Pack32LE(block[8], block[9], block[10], block[11]),
        OpCodes.Pack32LE(block[12], block[13], block[14], block[15])
      ];
      decryptWords(X, this._tables, this._inv);
      return [...OpCodes.Unpack32LE(X[0]), ...OpCodes.Unpack32LE(X[1]),
              ...OpCodes.Unpack32LE(X[2]), ...OpCodes.Unpack32LE(X[3])];
    }
  }

