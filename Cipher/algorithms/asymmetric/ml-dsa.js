/*
 * ML-DSA Implementation
 * NIST FIPS 204 - Module-Lattice-Based Digital Signature Algorithm
 * Compatible with AlgorithmFramework
 * (c)2006-2025 Hawkynt
 *
 * FIPS 204 is the standardised form of CRYSTALS-Dilithium, so the lattice half
 * of this scheme is not written twice. The ring arithmetic over
 * Z_q[X]/(X^256+1), the NTT, the samplers, the rejection loop and the section 7
 * packing all live in dilithium.js, which registers them under the round-3
 * name. This file is the FIPS 204 registration: it calls straight into that
 * same core and adds only what the standard layers on top of it, which is the
 * message pre-processing and the domain separation.
 *
 * That layer is the whole of the difference between the two registrations, and
 * it is not cosmetic. Round-3 Dilithium had no context string and no pre-hash
 * variant; FIPS 204 signs 0x00 || |ctx| || ctx || M rather than M, so the two
 * produce different signatures over the same message.
 *
 * Four interfaces, selected by messageEncoding:
 *
 *   'pure'        ML-DSA.Sign / ML-DSA.Verify, section 5.2. The message
 *                 representative is 0x00 || |ctx| || ctx || M. This is the
 *                 default, and it is what an application should use.
 *   'preHash'     HashML-DSA, section 5.4, for a signer that must hash the
 *                 message before it reaches the signing device. The
 *                 representative is 0x01 || |ctx| || ctx || OID || PH(M), the
 *                 OID naming which of the twelve approved hash functions
 *                 produced the digest.
 *   'internal'    ML-DSA.Sign_internal / Verify_internal, section 6. The fed
 *                 bytes are the representative, with no domain separation
 *                 added. This is the interface the ACVP internal vectors and
 *                 any higher-level protocol that does its own encoding use.
 *   'externalMu'  ExternalMu-ML-DSA. A 64 byte mu is fed in place of a
 *                 message, having been bound to the key elsewhere, so that a
 *                 large message never has to reach the device holding the
 *                 private key.
 *
 * Verified against the NIST ACVP FIPS 204 vector sets (usnistgov/ACVP-Server,
 * gen-val/json-files/ML-DSA-{keyGen,sigGen,sigVer}-FIPS204). Every published
 * case of all three sets passes, over all three parameter sets, both the
 * deterministic and the hedged variant, and all twelve pre-hash functions:
 *
 *   ML-DSA-keyGen-FIPS204   75/75   seed to public key and to private key
 *   ML-DSA-sigGen-FIPS204  360/360  pure, pre-hash, internal and external mu
 *   ML-DSA-sigVer-FIPS204  180/180  including every published negative case
 *
 * The subset committed below is deliberately the half the Dilithium
 * registration's own vectors do not reach: pre-hash across the SHA-2, SHA-3 and
 * SHAKE families, external mu both deterministic and hedged, and the published
 * rejections.
 */

