  function Mul64(a, b) {
    return OpCodes.AndN(a * b, MASK64);
  }

  // Bitwise complement inside 64 bits, expressed as XOR with the all-ones word
  function Not64(a) {
    return OpCodes.XorN(a, MASK64);
  }

